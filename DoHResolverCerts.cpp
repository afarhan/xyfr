//                                          GlobalSign Root CA)
//
// We pin three roots: the SSL.com ECC root (Cloudflare), GTS Root R4
// (Google direct), and GlobalSign Root CA (Google cross-signed path).
// GlobalSign Root CA expires 2028-01-28 -- the GTS R4 alternative
